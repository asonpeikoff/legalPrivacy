#!/usr/bin/env python3
"""Maintainer tool: rebuild noisycricket/ua_catalog.py from the official release calendars.

Sources (fetched live when you run this):
  Chrome    https://chromiumdash.appspot.com/fetch_releases  (Stable, Windows, per milestone)
  Firefox   https://product-details.mozilla.org/1.0/firefox_history_major_releases.json
            https://product-details.mozilla.org/1.0/firefox_versions.json  (ESR)

Keeps every release from the last WINDOW_DAYS (two years plus a margin). Commonness
is modelled, not measured: each release's weight decays with how many releases ago it
shipped, so the newest two or three majors dominate, as they do in real populations.
Re-run every few months; commit the regenerated module.
"""
import datetime as dt
import json
import sys
import urllib.request
from pathlib import Path

WINDOW_DAYS = 730 + 60          # "at least 2 years"
CHROME_DECAY = 0.55             # weight multiplier per release older than the newest
FIREFOX_DECAY = 0.60
CHROMIUM_SHARE = 0.10           # Chromium-branded builds, relative to Chrome
FIREFOX_ESR_SHARE = 0.25        # ESR is common in organisations, relative to Firefox stable
WEIGHT_FLOOR = 0.004            # every release in the window stays possible, the old ones rarely
OUT = Path(__file__).resolve().parents[1] / "noisycricket" / "ua_catalog.py"


def _get(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "noisyCricket-maintainer"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def chrome_majors(cutoff: dt.date) -> dict[int, dt.date]:
    """First stable date for each Chrome major released since cutoff."""
    out: dict[int, dt.date] = {}
    offset = 0
    while True:
        rows = _get("https://chromiumdash.appspot.com/fetch_releases?channel=Stable&platform=Windows"
                    f"&num=200&offset={offset}")
        if not rows:
            break
        oldest = None
        for r in rows:
            d = dt.datetime.fromtimestamp(r["time"] / 1000, dt.timezone.utc).date()
            m = int(r["milestone"])
            if d >= cutoff:
                out[m] = min(out.get(m, d), d)
            oldest = d if oldest is None else min(oldest, d)
        if oldest is not None and oldest < cutoff:
            break
        offset += len(rows)
    return out


def firefox_majors(cutoff: dt.date) -> dict[int, dt.date]:
    hist = _get("https://product-details.mozilla.org/1.0/firefox_history_major_releases.json")
    out = {}
    for ver, day in hist.items():
        d = dt.date.fromisoformat(day)
        major = int(ver.split(".")[0])
        if d >= cutoff and ver.endswith(".0"):
            out[major] = d
    return out


# Firefox ESR branches Mozilla has published; add the next one when it is declared.
KNOWN_ESR_MAJORS = [115, 128, 140, 153]


def firefox_esr(cutoff: dt.date, hist: dict[int, dt.date]) -> dict[int, dt.date]:
    """ESR majors whose first stable release falls inside the window (dates from the history file)."""
    cur = _get("https://product-details.mozilla.org/1.0/firefox_versions.json")
    majors = set(KNOWN_ESR_MAJORS) | {int(cur["FIREFOX_ESR"].split(".")[0])}
    return {m: hist[m] for m in majors if m in hist and hist[m] >= cutoff}


def weighted(majors: dict[int, dt.date], decay: float, share: float = 1.0) -> list[tuple[int, float]]:
    ordered = sorted(majors, reverse=True)
    return [(m, round(share * max(decay ** i, WEIGHT_FLOOR), 4)) for i, m in enumerate(ordered)]


def main() -> int:
    today = dt.date.today()
    cutoff = today - dt.timedelta(days=WINDOW_DAYS)
    chrome = chrome_majors(cutoff)
    ff_all = firefox_majors(dt.date(1990, 1, 1))
    ff = {m: d for m, d in ff_all.items() if d >= cutoff}
    esr = firefox_esr(cutoff, ff_all)
    if len(chrome) < 6 or len(ff) < 6:
        print("Refusing to write: too few releases came back.", file=sys.stderr)
        return 1

    lines = [
        '"""GENERATED by tools/build_ua_catalog.py. Do not edit by hand.',
        "",
        f"Built {today.isoformat()} from chromiumdash.appspot.com and product-details.mozilla.org.",
        f"Window: releases since {cutoff.isoformat()} (about two years).",
        "Weights model how common each version is (newest majors dominate); they are not measured shares.",
        '"""',
        "",
        "# (major, first stable release date, relative weight)",
        "CHROME = [",
        *[f"    ({m}, {chrome[m].isoformat()!r}, {w}),".replace("'", '"') for m, w in
          sorted(weighted(chrome, CHROME_DECAY), reverse=True)],
        "]",
        "",
        "CHROMIUM = [          # Chromium-branded builds (Linux distributions), same majors",
        *[f"    ({m}, {chrome[m].isoformat()!r}, {w}),".replace("'", '"') for m, w in
          sorted(weighted(chrome, CHROME_DECAY, CHROMIUM_SHARE), reverse=True)],
        "]",
        "",
        "FIREFOX = [",
        *[f"    ({m}, {ff[m].isoformat()!r}, {w}),".replace("'", '"') for m, w in
          sorted(weighted(ff, FIREFOX_DECAY), reverse=True)],
        "]",
        "",
        "FIREFOX_ESR = [",
        *[f"    ({m}, {esr[m].isoformat()!r}, {w}),".replace("'", '"') for m, w in
          sorted(weighted(esr, 0.5, FIREFOX_ESR_SHARE), reverse=True)],
        "]",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} (Chrome {len(chrome)}, Firefox {len(ff)}, ESR {len(esr)} majors).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
